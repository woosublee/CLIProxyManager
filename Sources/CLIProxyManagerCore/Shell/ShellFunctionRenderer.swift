import Foundation

public enum ShellFunctionRendererError: LocalizedError, Equatable {
    case duplicateFunctionNames([String])
    case invalidFunctionName(String)
    case invalidPort(Int)

    public var errorDescription: String? {
        switch self {
        case .duplicateFunctionNames(let names):
            let list = names.map { "`\($0)`" }.joined(separator: ", ")
            return "Command name \(list) is already used by another provider."
        case .invalidFunctionName(let name):
            return "Invalid command name `\(name)`. Use lowercase ASCII letters, numbers, and underscores. The first character must be a lowercase letter or underscore."
        case .invalidPort(let port):
            return "Invalid port `\(port)`. Use a value from 1 to 65535."
        }
    }
}

public enum ShellCommandNameValidator {
    public static func validate(_ functionNames: [String]) throws {
        try functionNames.forEach(validate)

        var seen: Set<String> = []
        var duplicates: [String] = []
        for functionName in functionNames {
            if seen.contains(functionName), !duplicates.contains(functionName) {
                duplicates.append(functionName)
            }
            seen.insert(functionName)
        }

        guard duplicates.isEmpty else {
            throw ShellFunctionRendererError.duplicateFunctionNames(duplicates)
        }
    }

    public static func validate(_ functionName: String) throws {
        guard let firstCharacter = functionName.first else {
            throw ShellFunctionRendererError.invalidFunctionName(functionName)
        }

        let firstCharacterIsValid = firstCharacter.isASCII && (firstCharacter.isLowercase || firstCharacter == "_")
        let remainingCharactersAreValid = functionName.dropFirst().allSatisfy { character in
            character.isASCII && (character.isLowercase || character.isNumber || character == "_")
        }

        guard firstCharacterIsValid && remainingCharactersAreValid else {
            throw ShellFunctionRendererError.invalidFunctionName(functionName)
        }
    }
}

public struct ShellFunctionRenderer: Sendable {
    private static let defaultClaudeOpusModel = "claude-opus-4-7"
    private static let defaultClaudeSonnetModel = "claude-sonnet-4-6"
    private static let defaultClaudeHaikuModel = "claude-haiku-4-5-20251001"

    public struct EnabledFunctions: Sendable {
        public var claudeOAuth: Bool
        public var codex: Bool
        public var claudeAPI: Bool

        public init(claudeOAuth: Bool, codex: Bool, claudeAPI: Bool) {
            self.claudeOAuth = claudeOAuth
            self.codex = codex
            self.claudeAPI = claudeAPI
        }

        public static let none = EnabledFunctions(claudeOAuth: false, codex: false, claudeAPI: false)
    }

    private let config: AppConfig
    private let helperCommand: String
    private let enabledFunctions: EnabledFunctions

    public init(config: AppConfig, helperCommand: String, includeClaudeAPI: Bool = false) {
        self.init(
            config: config,
            helperCommand: helperCommand,
            enabledFunctions: EnabledFunctions(claudeOAuth: true, codex: true, claudeAPI: includeClaudeAPI)
        )
    }

    public init(config: AppConfig, helperCommand: String, enabledFunctions: EnabledFunctions) {
        self.config = config
        self.helperCommand = helperCommand
        self.enabledFunctions = enabledFunctions
    }

    public func render() throws -> String {
        try ShellCommandNameValidator.validate(functionNamesToRender())
        try validate(port: config.port)

        let helperCommand = shellSingleQuoted(helperCommand)
        var script = """
        # Generated by CLIProxyAPI Manager. Do not edit this file manually.
        # Edit profiles in the CLIProxyAPI Manager app instead.

        """

        if config.oauthCommandProfiles.isEmpty {
            script += renderLegacyOAuthFunctions()
        } else {
            for commandProfile in oauthCommandProfilesToRender() {
                script += renderOAuthFunction(commandProfile)
            }
        }

        if enabledFunctions.claudeAPI, hasCommandName(config.commands.ccapi) {
            let claudeCommand = config.includeDangerouslySkipPermissions
                ? "claude --dangerously-skip-permissions \"$@\""
                : "claude \"$@\""
            script += """
            \(config.commands.ccapi)() {
              local anthropic_auth_token
              if ! anthropic_auth_token="$( \(helperCommand) secret get claude-api-key )"; then
                echo "Cannot read the Claude API key. Save the API key in CLIProxyAPI Manager."
                return 1
              fi

              ANTHROPIC_AUTH_TOKEN="$anthropic_auth_token" \\
              ANTHROPIC_MODEL=\(shellSingleQuoted(config.ccapi.model)) \\
              \(claudeCommand)
            }

            """
        }

        return script
    }

    private func renderLegacyOAuthFunctions() -> String {
        let claudeCommand = config.includeDangerouslySkipPermissions
            ? "claude --dangerously-skip-permissions \"$@\""
            : "claude \"$@\""
        let port = config.port
        let opusModel = config.ccodex.opus.modelIdentifier
        let sonnetModel = config.ccodex.sonnet.modelIdentifier
        let haikuModel = config.ccodex.haiku.modelIdentifier
        let claudeOpusModel = Self.defaultClaudeOpusModel
        let claudeSonnetModel = Self.defaultClaudeSonnetModel
        let claudeHaikuModel = Self.defaultClaudeHaikuModel

        var script = ""
        if enabledFunctions.claudeOAuth, hasCommandName(config.commands.cc) {
            script += """
            \(config.commands.cc)() {
              if ! curl -sf -H 'Authorization: Bearer sk-dummy' "http://127.0.0.1:\(port)/v1/models" >/dev/null; then
                echo "CLIProxyAPI Manager is not running or the Claude OAuth profile is not connected. Open the app to check the status."
                return 1
              fi

              ANTHROPIC_BASE_URL="http://127.0.0.1:\(port)" \\
              ANTHROPIC_AUTH_TOKEN='sk-dummy' \\
              ANTHROPIC_DEFAULT_OPUS_MODEL=\(shellSingleQuoted(claudeOpusModel)) \\
              ANTHROPIC_DEFAULT_SONNET_MODEL=\(shellSingleQuoted(claudeSonnetModel)) \\
              ANTHROPIC_DEFAULT_HAIKU_MODEL=\(shellSingleQuoted(claudeHaikuModel)) \\
              \(claudeCommand)
            }

            """
        }

        if enabledFunctions.codex, hasCommandName(config.commands.ccodex) {
            script += """
            \(config.commands.ccodex)() {
              if ! curl -sf -H 'Authorization: Bearer sk-dummy' "http://127.0.0.1:\(port)/v1/models" >/dev/null; then
                echo "CLIProxyAPI Manager is not running or authentication settings are invalid. Open the app to check the status."
                return 1
              fi

              ANTHROPIC_BASE_URL="http://127.0.0.1:\(port)" \\
              ANTHROPIC_AUTH_TOKEN='sk-dummy' \\
              ANTHROPIC_DEFAULT_OPUS_MODEL=\(shellSingleQuoted(opusModel)) \\
              ANTHROPIC_DEFAULT_SONNET_MODEL=\(shellSingleQuoted(sonnetModel)) \\
              ANTHROPIC_DEFAULT_HAIKU_MODEL=\(shellSingleQuoted(haikuModel)) \\
              \(claudeCommand)
            }

            """
        }
        return script
    }

    private func renderOAuthFunction(_ commandProfile: AppConfig.OAuthCommandProfile) -> String {
        let claudeCommand = commandProfile.dangerousPermissionsEnabled
            ? "claude --dangerously-skip-permissions \"$@\""
            : "claude \"$@\""
        let port = config.port
        let commandName = commandProfile.commandName
        let errorMessage = commandProfile.provider == .codex
            ? "CLIProxyAPI Manager is not running or authentication settings are invalid. Open the app to check the status."
            : "CLIProxyAPI Manager is not running or the Claude OAuth profile is not connected. Open the app to check the status."
        let models = defaultModels(for: commandProfile)

        return """
        \(commandName)() {
          if ! curl -sf -H 'Authorization: Bearer sk-dummy' "http://127.0.0.1:\(port)/v1/models" >/dev/null; then
            echo "\(errorMessage)"
            return 1
          fi

          ANTHROPIC_BASE_URL="http://127.0.0.1:\(port)" \\
          ANTHROPIC_AUTH_TOKEN='sk-dummy' \\
          ANTHROPIC_DEFAULT_OPUS_MODEL=\(shellSingleQuoted(models.opus)) \\
          ANTHROPIC_DEFAULT_SONNET_MODEL=\(shellSingleQuoted(models.sonnet)) \\
          ANTHROPIC_DEFAULT_HAIKU_MODEL=\(shellSingleQuoted(models.haiku)) \\
          \(claudeCommand)
        }

        """
    }

    private func defaultModels(for commandProfile: AppConfig.OAuthCommandProfile) -> (opus: String, sonnet: String, haiku: String) {
        switch commandProfile.provider {
        case .claude:
            return (
                prefixedModel(Self.defaultClaudeOpusModel, prefix: commandProfile.modelPrefix),
                prefixedModel(Self.defaultClaudeSonnetModel, prefix: commandProfile.modelPrefix),
                prefixedModel(Self.defaultClaudeHaikuModel, prefix: commandProfile.modelPrefix)
            )
        case .codex:
            let codex = commandProfile.codex ?? config.ccodex
            return (
                prefixedModel(codex.opus.modelIdentifier, prefix: commandProfile.modelPrefix),
                prefixedModel(codex.sonnet.modelIdentifier, prefix: commandProfile.modelPrefix),
                prefixedModel(codex.haiku.modelIdentifier, prefix: commandProfile.modelPrefix)
            )
        }
    }

    private func prefixedModel(_ model: String, prefix: String) -> String {
        let trimmedPrefix = prefix.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmedPrefix.isEmpty else { return model }
        return "\(trimmedPrefix)/\(model)"
    }

    private func functionNamesToRender() -> [String] {
        var names: [String]
        if config.oauthCommandProfiles.isEmpty {
            names = []
            if enabledFunctions.claudeOAuth, hasCommandName(config.commands.cc) { names.append(config.commands.cc) }
            if enabledFunctions.codex, hasCommandName(config.commands.ccodex) { names.append(config.commands.ccodex) }
        } else {
            names = oauthCommandProfilesToRender().map(\.commandName)
        }
        if enabledFunctions.claudeAPI, hasCommandName(config.commands.ccapi) { names.append(config.commands.ccapi) }
        return names
    }

    private func oauthCommandProfilesToRender() -> [AppConfig.OAuthCommandProfile] {
        config.oauthCommandProfiles.filter { commandProfile in
            guard commandProfile.isEnabled, hasCommandName(commandProfile.commandName) else { return false }
            switch commandProfile.provider {
            case .claude:
                return enabledFunctions.claudeOAuth
            case .codex:
                return enabledFunctions.codex
            }
        }
    }

    private func hasCommandName(_ commandName: String) -> Bool {
        !commandName.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    private func validate(port: Int) throws {
        guard (1...65_535).contains(port) else {
            throw ShellFunctionRendererError.invalidPort(port)
        }
    }

    private func shellSingleQuoted(_ value: String) -> String {
        if value.isEmpty { return "''" }
        return "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
}
